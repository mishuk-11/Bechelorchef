-- Bachelor Chef ERP — initial schema.
-- All timestamps are stored as TIMESTAMPTZ (UTC instants). Money uses NUMERIC, never floating point.
-- Users are never hard-deleted (soft delete + anonymisation), so user FKs use RESTRICT or SET NULL
-- and never cascade into published community content.

-- ---------------------------------------------------------------------------
-- Identity
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(254) NOT NULL,
    phone_number    VARCHAR(20),
    password_hash   VARCHAR(100),
    google_id       VARCHAR(100),
    role            VARCHAR(10)  NOT NULL DEFAULT 'USER',
    avatar_url      VARCHAR(500),
    avatar_asset_id VARCHAR(255),
    bio             VARCHAR(500),
    status          VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    deleted_at      TIMESTAMPTZ,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_phone UNIQUE (phone_number),
    CONSTRAINT uq_users_google UNIQUE (google_id),
    CONSTRAINT ck_users_email_normalized CHECK (email = lower(btrim(email))),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    CONSTRAINT ck_users_credentials CHECK (password_hash IS NOT NULL OR google_id IS NOT NULL OR status = 'DELETED')
);
CREATE INDEX ix_users_status ON users (status);
CREATE INDEX ix_users_created_at ON users (created_at);

CREATE TABLE refresh_tokens (
    token_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)    NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------------
-- Catalogue
-- ---------------------------------------------------------------------------
CREATE TABLE ingredients (
    ingredient_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80)  NOT NULL,
    normalized_name VARCHAR(80)  NOT NULL,
    category        VARCHAR(40),
    default_unit    VARCHAR(20),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_ingredients_normalized UNIQUE (normalized_name),
    CONSTRAINT ck_ingredients_normalized CHECK (normalized_name = lower(btrim(normalized_name)) AND length(normalized_name) > 0)
);
CREATE INDEX ix_ingredients_category_active ON ingredients (category, active);

CREATE TABLE tags (
    tag_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(40) NOT NULL,
    normalized_name VARCHAR(40) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_tags_normalized UNIQUE (normalized_name),
    CONSTRAINT ck_tags_normalized CHECK (normalized_name = lower(btrim(normalized_name)) AND length(normalized_name) > 0)
);

-- ---------------------------------------------------------------------------
-- Imports (created before recipes so recipes can reference their source job)
-- ---------------------------------------------------------------------------
CREATE TABLE bulk_upload_jobs (
    job_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by      BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    source_filename  VARCHAR(255) NOT NULL,
    file_type        VARCHAR(10)  NOT NULL,
    file_sha256      VARCHAR(64),
    file_size_bytes  BIGINT,
    status           VARCHAR(30)  NOT NULL,
    total_rows       INTEGER      NOT NULL DEFAULT 0,
    valid_rows       INTEGER      NOT NULL DEFAULT 0,
    imported_rows    INTEGER      NOT NULL DEFAULT 0,
    failed_rows      INTEGER      NOT NULL DEFAULT 0,
    skipped_rows     INTEGER      NOT NULL DEFAULT 0,
    summary          VARCHAR(1000),
    staged_payload   TEXT,
    started_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at      TIMESTAMPTZ,
    version          BIGINT       NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_jobs_file_type CHECK (file_type IN ('CSV', 'JSON')),
    CONSTRAINT ck_jobs_status CHECK (status IN ('PREVIEWED', 'PROCESSING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED', 'EXPIRED')),
    CONSTRAINT ck_jobs_counts CHECK (total_rows BETWEEN 0 AND 500 AND imported_rows >= 0 AND failed_rows >= 0 AND skipped_rows >= 0)
);
CREATE INDEX ix_jobs_started_at ON bulk_upload_jobs (started_at DESC);
CREATE INDEX ix_jobs_status ON bulk_upload_jobs (status);

CREATE TABLE bulk_upload_errors (
    error_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       BIGINT       NOT NULL REFERENCES bulk_upload_jobs (job_id) ON DELETE CASCADE,
    row_number   INTEGER,
    line_number  INTEGER,
    field_name   VARCHAR(80),
    severity     VARCHAR(10)  NOT NULL DEFAULT 'ERROR',
    error_code   VARCHAR(40)  NOT NULL,
    message      VARCHAR(500) NOT NULL,
    row_excerpt  VARCHAR(300),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_errors_severity CHECK (severity IN ('ERROR', 'WARNING'))
);
CREATE INDEX ix_errors_job ON bulk_upload_errors (job_id, row_number);

-- ---------------------------------------------------------------------------
-- Recipes
-- ---------------------------------------------------------------------------
CREATE TABLE recipes (
    recipe_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(150)  NOT NULL,
    normalized_title    VARCHAR(150)  NOT NULL,
    description         TEXT,
    prep_time_mins      INTEGER       NOT NULL,
    cook_time_mins      INTEGER       NOT NULL,
    total_time_mins     INTEGER       NOT NULL,
    difficulty          VARCHAR(10)   NOT NULL,
    estimated_cost_bdt  NUMERIC(10,2) NOT NULL,
    base_servings       INTEGER       NOT NULL,
    image_url           VARCHAR(500),
    image_asset_id      VARCHAR(255),
    is_official         BOOLEAN       NOT NULL DEFAULT FALSE,
    is_sample           BOOLEAN       NOT NULL DEFAULT FALSE,
    status              VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    moderation_note     VARCHAR(1000),
    created_by          BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    approved_by         BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    approved_at         TIMESTAMPTZ,
    import_job_id       BIGINT REFERENCES bulk_upload_jobs (job_id) ON DELETE SET NULL,
    rating_avg          NUMERIC(3,2)  NOT NULL DEFAULT 0,
    rating_count        INTEGER       NOT NULL DEFAULT 0,
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_recipes_title CHECK (char_length(btrim(title)) BETWEEN 3 AND 150),
    CONSTRAINT ck_recipes_description CHECK (description IS NULL OR char_length(description) <= 5000),
    CONSTRAINT ck_recipes_prep CHECK (prep_time_mins BETWEEN 0 AND 60),
    CONSTRAINT ck_recipes_cook CHECK (cook_time_mins BETWEEN 1 AND 60),
    CONSTRAINT ck_recipes_total CHECK (total_time_mins = prep_time_mins + cook_time_mins AND total_time_mins <= 60),
    CONSTRAINT ck_recipes_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT ck_recipes_cost CHECK (estimated_cost_bdt >= 0 AND estimated_cost_bdt <= 100000),
    CONSTRAINT ck_recipes_servings CHECK (base_servings BETWEEN 1 AND 20),
    CONSTRAINT ck_recipes_status CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'ARCHIVED')),
    CONSTRAINT ck_recipes_rating CHECK (rating_avg BETWEEN 0 AND 5 AND rating_count >= 0),
    CONSTRAINT ck_recipes_image_https CHECK (image_url IS NULL OR image_url LIKE 'https://%')
);
CREATE INDEX ix_recipes_status_total ON recipes (status, total_time_mins);
CREATE INDEX ix_recipes_created_by ON recipes (created_by);
CREATE INDEX ix_recipes_created_at ON recipes (created_at DESC);
CREATE INDEX ix_recipes_status_cost ON recipes (status, estimated_cost_bdt);
CREATE INDEX ix_recipes_status_rating ON recipes (status, rating_avg DESC);
CREATE INDEX ix_recipes_normalized_title ON recipes (normalized_title);

CREATE TABLE recipe_ingredients (
    recipe_id     BIGINT        NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
    ingredient_id BIGINT        NOT NULL REFERENCES ingredients (ingredient_id) ON DELETE RESTRICT,
    quantity      NUMERIC(10,3) NOT NULL,
    unit          VARCHAR(20)   NOT NULL,
    is_optional   BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order    INTEGER       NOT NULL DEFAULT 0,
    PRIMARY KEY (recipe_id, ingredient_id),
    CONSTRAINT ck_ri_quantity CHECK (quantity > 0),
    CONSTRAINT ck_ri_unit CHECK (char_length(btrim(unit)) BETWEEN 1 AND 20)
);
CREATE INDEX ix_ri_ingredient ON recipe_ingredients (ingredient_id);

CREATE TABLE recipe_steps (
    step_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id        BIGINT       NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
    step_number      INTEGER      NOT NULL,
    instruction_text TEXT         NOT NULL,
    image_url        VARCHAR(500),
    image_asset_id   VARCHAR(255),
    CONSTRAINT uq_recipe_steps UNIQUE (recipe_id, step_number),
    CONSTRAINT ck_steps_number CHECK (step_number >= 1),
    CONSTRAINT ck_steps_text CHECK (char_length(btrim(instruction_text)) BETWEEN 1 AND 2000),
    CONSTRAINT ck_steps_image_https CHECK (image_url IS NULL OR image_url LIKE 'https://%')
);

CREATE TABLE recipe_tags (
    recipe_id BIGINT NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
    tag_id    BIGINT NOT NULL REFERENCES tags (tag_id) ON DELETE CASCADE,
    PRIMARY KEY (recipe_id, tag_id)
);
CREATE INDEX ix_recipe_tags_tag ON recipe_tags (tag_id);

-- ---------------------------------------------------------------------------
-- Community
-- ---------------------------------------------------------------------------
CREATE TABLE reviews (
    review_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id          BIGINT       NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
    user_id            BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    rating             INTEGER      NOT NULL,
    comment            VARCHAR(2000),
    photo_url          VARCHAR(500),
    photo_asset_id     VARCHAR(255),
    status             VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    moderation_reason  VARCHAR(500),
    moderated_by       BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    moderated_at       TIMESTAMPTZ,
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_reviews_recipe_user UNIQUE (recipe_id, user_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REMOVED')),
    CONSTRAINT ck_reviews_photo_https CHECK (photo_url IS NULL OR photo_url LIKE 'https://%')
);
CREATE INDEX ix_reviews_recipe_status ON reviews (recipe_id, status);
CREATE INDEX ix_reviews_user_created ON reviews (user_id, created_at DESC);
CREATE INDEX ix_reviews_status_created ON reviews (status, created_at);

CREATE TABLE content_reports (
    report_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id      BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    target_type      VARCHAR(10)  NOT NULL,
    target_id        BIGINT       NOT NULL,
    reason           VARCHAR(500) NOT NULL,
    status           VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    resolved_by      BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    resolution_note  VARCHAR(500),
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_reports_target CHECK (target_type IN ('RECIPE', 'REVIEW')),
    CONSTRAINT ck_reports_status CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED'))
);
-- One open report per reporter and target; reporting again after resolution is allowed.
CREATE UNIQUE INDEX uq_reports_open ON content_reports (reporter_id, target_type, target_id) WHERE status = 'OPEN';
CREATE INDEX ix_reports_status_created ON content_reports (status, created_at);
CREATE INDEX ix_reports_target ON content_reports (target_type, target_id);

-- ---------------------------------------------------------------------------
-- Personal cooking
-- ---------------------------------------------------------------------------
CREATE TABLE saved_recipes (
    user_id   BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    recipe_id BIGINT      NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
    saved_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, recipe_id)
);
CREATE INDEX ix_saved_user_saved_at ON saved_recipes (user_id, saved_at DESC);

CREATE TABLE user_cooked_history (
    history_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    recipe_id   BIGINT        NOT NULL REFERENCES recipes (recipe_id) ON DELETE RESTRICT,
    cooked_on   TIMESTAMPTZ   NOT NULL,
    notes       VARCHAR(1000),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_history_user_cooked ON user_cooked_history (user_id, cooked_on DESC);
CREATE INDEX ix_history_recipe ON user_cooked_history (recipe_id);
CREATE INDEX ix_history_cooked_on ON user_cooked_history (cooked_on);

CREATE TABLE user_goals (
    goal_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    title                VARCHAR(120) NOT NULL,
    target_count         INTEGER      NOT NULL,
    target_month         DATE         NOT NULL,
    count_mode           VARCHAR(20)  NOT NULL DEFAULT 'UNIQUE_RECIPES',
    tag_id               BIGINT REFERENCES tags (tag_id) ON DELETE SET NULL,
    max_total_time_mins  INTEGER,
    completed_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_goals_target CHECK (target_count BETWEEN 1 AND 30),
    CONSTRAINT ck_goals_month CHECK (EXTRACT(DAY FROM target_month) = 1),
    CONSTRAINT ck_goals_mode CHECK (count_mode IN ('UNIQUE_RECIPES', 'COOK_EVENTS')),
    CONSTRAINT ck_goals_max_time CHECK (max_total_time_mins IS NULL OR max_total_time_mins BETWEEN 1 AND 60),
    CONSTRAINT ck_goals_title CHECK (char_length(btrim(title)) BETWEEN 3 AND 120)
);
CREATE INDEX ix_goals_user_month ON user_goals (user_id, target_month);

-- ---------------------------------------------------------------------------
-- Audit
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
    audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    action       VARCHAR(50)  NOT NULL,
    target_type  VARCHAR(30)  NOT NULL,
    target_id    BIGINT,
    details      VARCHAR(1000),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_created ON audit_logs (created_at DESC);
CREATE INDEX ix_audit_actor ON audit_logs (actor_id);
